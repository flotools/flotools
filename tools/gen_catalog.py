"""Generate Sources/FloToolsCore/Catalog+Generated.swift from the Keyboard Maestro export.

The catalog keeps every macro's UID, group and hotkeys exactly as in Keyboard Maestro, so ported Swift actions only need to be attached by UID.

Usage: .venv/bin/python -I tools/gen_catalog.py [reference/Flo Tools.kmmacros] [Sources/FloToolsCore/Catalog+Generated.swift]
"""

import plistlib
import sys
from pathlib import Path


def swift_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return f'"{s}"'


def title_condition(g):
    kind = g.get("FocussedWindowConditionType")
    title = g.get("FocussedWindowTitle")
    if not title:
        return ".any"
    mapping = {"TitleIs": "is", "TitleContains": "contains", "TitleMatches": "matches"}
    if kind not in mapping:
        raise SystemExit(f"unknown window condition {kind!r} in group {g['Name']!r}")
    return f".{mapping[kind]}({swift_str(title)})"


def main():
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "reference/Flo Tools.kmmacros")
    dst = Path(sys.argv[2] if len(sys.argv) > 2 else "Sources/FloToolsCore/Catalog+Generated.swift")
    data = plistlib.load(src.open("rb"))

    groups = {}
    macros = []
    for g in data:
        name = g["Name"]
        if name not in groups:
            apps = [a["BundleIdentifier"] for a in g.get("Targeting", {}).get("TargetingApps", [])]
            if g.get("Targeting", {}).get("Targeting") not in (None, "Included", "All"):
                raise SystemExit(f"unsupported targeting in group {name!r}")
            groups[name] = (g.get("IsActive", True), apps, title_condition(g))
        for m in g.get("Macros", []):
            hot = []
            other = []
            for t in m.get("Triggers", []):
                if t["MacroTriggerType"] == "HotKey":
                    release = t.get("FireType", "Pressed") == "Released"
                    hot.append(f"HotKeyTrigger(KeyCombo(keyCode: {t['KeyCode']}, modifiers: {t['Modifiers']}), onRelease: {str(release).lower()})")
                else:
                    detail = t.get("ChangeType") or t.get("FireType2") or ""
                    other.append(swift_str(f"{t['MacroTriggerType']} {detail}".strip()))
            macros.append(
                f"        MacroInfo(uid: {swift_str(m['UID'])}, name: {swift_str(m.get('Name', ''))}, group: {swift_str(name)}, "
                f"enabledByDefault: {str(m.get('IsActive', True)).lower()}, hotKeys: [{', '.join(hot)}], otherTriggers: [{', '.join(other)}]),"
            )

    out = [
        "// Generated by tools/gen_catalog.py from reference/Flo Tools.kmmacros. Do not edit.",
        "",
        "public enum Catalog {",
        "    public static let groups: [MacroGroup] = [",
    ]
    for name, (active, apps, cond) in groups.items():
        out.append(
            f"        MacroGroup(name: {swift_str(name)}, enabledByDefault: {str(active).lower()}, "
            f"bundleIDs: [{', '.join(swift_str(a) for a in apps)}], title: {cond}),"
        )
    out += ["    ]", "", "    public static let macros: [MacroInfo] = ["]
    out += macros
    out += ["    ]", "}", ""]
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(out))
    print(f"wrote {len(groups)} groups and {len(macros)} macros to {dst}")


if __name__ == "__main__":
    main()
